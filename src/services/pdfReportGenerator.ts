import { jsPDF } from 'jspdf';
import { Finding, Asset, Scan } from '../types/security';

export interface ReportConfig {
  reportType: 'EXECUTIVE' | 'TECHNICAL' | 'COMBINED';
  title: string;
  targetAssets: Asset[];
  findings: Finding[];
  scans: Scan[];
  includeRemediation: boolean;
  includeTechnicalAppendix: boolean;
  includeMethodology: boolean;
  generatedBy: string;
}

export function generateSecurityReportPDF(config: ReportConfig): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = 210;
  const pageHeight = 297;
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  const primaryRed: [number, number, number] = [255, 53, 72];
  const darkBg: [number, number, number] = [9, 11, 15];
  const cardBg: [number, number, number] = [20, 25, 34];
  const textDark: [number, number, number] = [20, 25, 35];
  const textMuted: [number, number, number] = [100, 110, 125];

  const checkPageBreak = (neededHeight: number) => {
    if (y + neededHeight > pageHeight - margin - 15) {
      doc.addPage();
      y = margin;
      drawHeaderFooter();
    }
  };

  const drawHeaderFooter = () => {
    const pageNum = doc.getNumberOfPages();
    // Top tiny header line
    doc.setDrawColor(220, 225, 235);
    doc.setLineWidth(0.3);
    doc.line(margin, 12, pageWidth - margin, 12);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(255, 53, 72);
    doc.text('CODE RED TOOL', margin, 10);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(130, 140, 155);
    doc.text('DEFENSIVE VAPT & REMEDIATION REPORT', margin + 30, 10);

    const dateStr = new Date().toISOString().split('T')[0];
    doc.text(`CONFIDENTIAL • ${dateStr}`, pageWidth - margin, 10, { align: 'right' });

    // Footer
    doc.setDrawColor(220, 225, 235);
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);
    doc.setFontSize(8);
    doc.setTextColor(140, 150, 165);
    doc.text('Authorized Assessment Data • Proprietary & Confidential', margin, pageHeight - 8);
    doc.text(`Page ${pageNum}`, pageWidth - margin, pageHeight - 8, { align: 'right' });
  };

  // --- COVER HEADER ---
  drawHeaderFooter();

  // Red accent block
  doc.setFillColor(...primaryRed);
  doc.rect(margin, y, 4, 18, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(...textDark);
  doc.text(config.title, margin + 8, y + 8);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(...textMuted);
  const typeLabel = config.reportType === 'EXECUTIVE' 
    ? 'Executive Risk Summary' 
    : config.reportType === 'TECHNICAL' 
      ? 'Technical Vulnerability Assessment' 
      : 'Comprehensive Executive & Technical Report';
  doc.text(`${typeLabel} • Generated by ${config.generatedBy}`, margin + 8, y + 15);

  y += 26;

  // --- METADATA PANEL ---
  doc.setFillColor(245, 247, 250);
  doc.rect(margin, y, contentWidth, 24, 'F');
  doc.setDrawColor(220, 225, 235);
  doc.rect(margin, y, contentWidth, 24, 'D');

  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(100, 110, 125);
  doc.text('ASSESSED TARGETS', margin + 6, y + 6);
  doc.text('ASSESSMENT PROFILE', margin + 65, y + 6);
  doc.text('TOTAL FINDINGS', margin + 120, y + 6);
  doc.text('OVERALL POSTURE', margin + 155, y + 6);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...textDark);
  const targetNames = config.targetAssets.map(a => a.name).join(', ') || 'All Active Workspace Assets';
  doc.text(targetNames.length > 28 ? targetNames.substring(0, 26) + '...' : targetNames, margin + 6, y + 14);
  doc.text('Defensive Posture Audit', margin + 65, y + 14);

  const critCount = config.findings.filter(f => f.severity === 'CRITICAL').length;
  const highCount = config.findings.filter(f => f.severity === 'HIGH').length;
  const medCount = config.findings.filter(f => f.severity === 'MEDIUM').length;
  const lowCount = config.findings.filter(f => f.severity === 'LOW').length;

  doc.text(`${config.findings.length} Discovered`, margin + 120, y + 14);

  // Overall posture badge
  if (critCount > 0) {
    doc.setTextColor(220, 38, 38);
    doc.text('CRITICAL EXPOSURE', margin + 155, y + 14);
  } else if (highCount > 0) {
    doc.setTextColor(234, 88, 12);
    doc.text('ELEVATED RISK', margin + 155, y + 14);
  } else {
    doc.setTextColor(22, 163, 74);
    doc.text('STABLE / MANAGED', margin + 155, y + 14);
  }

  y += 32;

  // --- EXECUTIVE SUMMARY SECTION ---
  if (config.reportType === 'EXECUTIVE' || config.reportType === 'COMBINED') {
    checkPageBreak(50);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(...textDark);
    doc.text('1. Executive Risk Overview', margin, y);
    y += 6;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(60, 70, 85);
    const summaryLines = doc.splitTextToSize(
      `This report documents findings from defensive, authorized vulnerability assessments conducted across the specified assets. Analysis identified ${config.findings.length} distinct findings (${critCount} Critical, ${highCount} High, ${medCount} Medium, ${lowCount} Low). Critical and High findings warrant priority remediation within the current development cycle to safeguard sensitive data and prevent potential authorization bypass or unauthorized request forgery.`,
      contentWidth
    );
    doc.text(summaryLines, margin, y);
    y += summaryLines.length * 5 + 4;

    // Severity metric table
    checkPageBreak(30);
    doc.setFillColor(248, 250, 252);
    doc.rect(margin, y, contentWidth, 18, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.rect(margin, y, contentWidth, 18, 'D');

    const colW = contentWidth / 4;
    const severities = [
      { label: 'Critical', count: critCount, color: [220, 38, 38] },
      { label: 'High', count: highCount, color: [234, 88, 12] },
      { label: 'Medium', count: medCount, color: [202, 138, 4] },
      { label: 'Low / Info', count: lowCount, color: [37, 99, 235] }
    ];

    severities.forEach((s, idx) => {
      const colX = margin + idx * colW;
      doc.setFontSize(8);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(110, 120, 135);
      doc.text(s.label.toUpperCase(), colX + 8, y + 6);

      doc.setFontSize(12);
      doc.setTextColor(s.color[0], s.color[1], s.color[2]);
      doc.text(String(s.count), colX + 8, y + 14);
    });

    y += 26;
  }

  // --- TECHNICAL FINDINGS SECTION ---
  if (config.reportType === 'TECHNICAL' || config.reportType === 'COMBINED') {
    checkPageBreak(30);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(...textDark);
    doc.text(config.reportType === 'COMBINED' ? '2. Technical Vulnerability Register' : '1. Technical Vulnerability Register', margin, y);
    y += 8;

    config.findings.forEach((f, idx) => {
      checkPageBreak(55);

      // Card header
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, y, contentWidth, 12, 'F');
      doc.setDrawColor(220, 225, 235);
      doc.rect(margin, y, contentWidth, 12, 'D');

      // Severity tag
      const sevColor: [number, number, number] = 
        f.severity === 'CRITICAL' ? [220, 38, 38] :
        f.severity === 'HIGH' ? [234, 88, 12] :
        f.severity === 'MEDIUM' ? [202, 138, 4] : [37, 99, 235];

      doc.setFillColor(...sevColor);
      doc.rect(margin + 4, y + 3, 20, 6, 'F');
      doc.setFontSize(7.5);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(255, 255, 255);
      doc.text(f.severity, margin + 14, y + 7.2, { align: 'center' });

      // Title
      doc.setFontSize(9.5);
      doc.setTextColor(...textDark);
      doc.setFont('helvetica', 'bold');
      const truncatedTitle = f.title.length > 55 ? f.title.substring(0, 52) + '...' : f.title;
      doc.text(`${f.id}: ${truncatedTitle}`, margin + 28, y + 7.5);

      // Status
      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(110, 120, 135);
      doc.text(`Status: ${f.status} • Asset: ${f.assetName}`, pageWidth - margin - 4, y + 7.5, { align: 'right' });

      y += 15;

      // Endpoint & Evidence
      doc.setFontSize(8.5);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(70, 80, 95);
      doc.text('Affected Endpoint:', margin + 4, y);
      doc.setFont('courier', 'normal');
      doc.setTextColor(30, 41, 59);
      doc.text(f.affectedEndpoint, margin + 35, y);
      y += 5;

      doc.setFont('helvetica', 'bold');
      doc.setTextColor(70, 80, 95);
      doc.text('Business Impact:', margin + 4, y);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(60, 70, 85);
      const impactLines = doc.splitTextToSize(f.businessImpact, contentWidth - 36);
      doc.text(impactLines, margin + 35, y);
      y += impactLines.length * 4.5 + 2;

      if (f.simulatedAttackVector) {
        checkPageBreak(15);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(180, 83, 9);
        doc.text('Attack Simulation:', margin + 4, y);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(146, 64, 14);
        const simLines = doc.splitTextToSize(f.simulatedAttackVector, contentWidth - 36);
        doc.text(simLines, margin + 35, y);
        y += simLines.length * 4.5 + 2;
      }

      if (config.includeRemediation) {
        checkPageBreak(15);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(70, 80, 95);
        doc.text('Remediation:', margin + 4, y);
        doc.setFont('helvetica', 'normal');
        doc.setTextColor(22, 101, 52);
        const remLines = doc.splitTextToSize(f.remediationSummary, contentWidth - 36);
        doc.text(remLines, margin + 35, y);
        y += remLines.length * 4.5 + 4;
      }

      y += 3;
    });
  }

  // --- METHODOLOGY & LIMITATIONS DISCLAIMER ---
  if (config.includeMethodology) {
    checkPageBreak(40);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(...textDark);
    doc.text('Assessment Methodology & Scope Limitations', margin, y);
    y += 6;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 110, 125);
    const disclaimer = doc.splitTextToSize(
      'This assessment was executed exclusively against explicitly authorized target scopes utilizing defensive and passive security evaluation techniques. Automated security reviews provide point-in-time visibility into configuration baselines, known CVE advisories, and standard header policies. They do not constitute an exhaustive guarantee against sophisticated bespoke application attacks or multi-step business logic anomalies. Human security verification and continuous code review are recommended prior to release.',
      contentWidth
    );
    doc.text(disclaimer, margin, y);
    y += disclaimer.length * 4 + 4;
  }

  // Save PDF
  const filename = `CodeRed-${config.reportType.toLowerCase()}-report-${Date.now().toString().slice(-6)}.pdf`;
  doc.save(filename);
}
